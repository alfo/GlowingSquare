#!/usr/bin/env python3
"""Turn src/project/assets/logo.svg into src/project/project_assets.cpp:
the SVG itself (the web header's mark), a 32 px favicon and a 180 px
apple-touch-icon as PNGs.

Needs rsvg-convert (librsvg) on the PATH. Run it again after changing the
logo; the generated file is committed so a build needs nothing but PlatformIO.

    python3 tools/gen_web_assets.py
"""
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
svg_path = root / "src/project/assets/logo.svg"
out_cpp = root / "src/project/project_assets.cpp"


def png(size):
    return subprocess.run(
        ["rsvg-convert", "-w", str(size), "-h", str(size), str(svg_path)],
        check=True, capture_output=True).stdout


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "\n".join(rows)


def main():
    svg = svg_path.read_text().strip()
    if "\n" in svg:
        svg = " ".join(line.strip() for line in svg.splitlines())
    svg_c = svg.replace("\\", "\\\\").replace('"', '\\"')
    fav, touch = png(32), png(180)
    out_cpp.write_text(
        "// Generated by tools/gen_web_assets.py from assets/logo.svg. Do not edit.\n"
        '#include "project/project_assets.h"\n\n'
        f'const char PROJECT_LOGO_SVG[] PROGMEM = "{svg_c}";\n\n'
        f"const uint8_t PROJECT_FAVICON_PNG[] PROGMEM = {{\n{c_bytes(fav)}\n}};\n"
        f"const size_t PROJECT_FAVICON_PNG_LEN = sizeof(PROJECT_FAVICON_PNG);\n\n"
        f"const uint8_t PROJECT_TOUCH_ICON_PNG[] PROGMEM = {{\n{c_bytes(touch)}\n}};\n"
        f"const size_t PROJECT_TOUCH_ICON_PNG_LEN = sizeof(PROJECT_TOUCH_ICON_PNG);\n")
    print(f"{out_cpp.relative_to(root)}: svg {len(svg)} B, favicon {len(fav)} B, touch icon {len(touch)} B")


if __name__ == "__main__":
    sys.exit(main())
